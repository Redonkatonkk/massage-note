const registeredCatalogNames = new Map<string, { kind: CatalogNameKind; translation: string }>();

function automaticCatalogNameTranslation(value: string): string {
  const source = value.trim();
  if (!/[\p{Script=Han}]/u.test(source)) return source;
  const exact = CATALOG_NAME_TRANSLATIONS[source];
  if (exact) return exact;

  const leadingDuration = source.match(/^(\d+)\s*(?:分钟|分)\s*(.+)$/u);
  if (leadingDuration) {
    const translatedName = automaticCatalogNameTranslation(leadingDuration[2]!);
    if (translatedName !== leadingDuration[2]) return `${leadingDuration[1]}-minute ${translatedName}`;
  }
  const trailingDuration = source.match(/^(.+?)\s*(\d+)\s*(?:分钟|分)$/u);
  if (trailingDuration) {
    const translatedName = automaticCatalogNameTranslation(trailingDuration[1]!);
    if (translatedName !== trailingDuration[1]) return `${trailingDuration[2]}-minute ${translatedName}`;
  }

  let translated = source.replace(/[+、／/]|(?:和|与)/gu, " & ");
  for (const [chinese, english] of CATALOG_NAME_PARTS) {
    translated = translated.replaceAll(chinese, ` ${english} `);
  }
  translated = translated.replace(/\s+/gu, " ").trim();
  return /[\p{Script=Han}]/u.test(translated) ? source : translated;
}

function registerCatalogName(value: unknown, kind: CatalogNameKind) {
  if (typeof value !== "string" || !value.trim()) return;
  const source = value.trim();
  registeredCatalogNames.set(source, {
    kind,
    translation: automaticCatalogNameTranslation(source),
  });
}

function registerCatalogGroup(value: unknown, kind: CatalogNameKind) {
  if (!Array.isArray(value)) return;
  for (const item of value) {
    if (!item || typeof item !== "object") continue;
    const record = item as Record<string, unknown>;
    registerCatalogName(record.fullName ?? record.name, kind);
    registerCatalogName(record.shortName, kind);
  }
}

/** Registers store-defined catalog strings before React renders their API payload. */
export function registerCatalogNamesFromPayload(payload: unknown, requestPath = "") {
  const visited = new WeakSet<object>();
  function visit(value: unknown) {
    if (!value || typeof value !== "object") return;
    if (visited.has(value)) return;
    visited.add(value);
    if (Array.isArray(value)) {
      value.forEach(visit);
      return;
    }
    const record = value as Record<string, unknown>;
    registerCatalogGroup(record.serviceItems, "service");
    registerCatalogGroup(record.addonItems, "addon");
    registerCatalogGroup(record.discountItems, "discount");
    if (record.serviceSnapshot && typeof record.serviceSnapshot === "object") {
      const snapshot = record.serviceSnapshot as Record<string, unknown>;
      registerCatalogName(snapshot.name, "service");
      registerCatalogName(snapshot.shortName, "service");
    }
    registerCatalogGroup(record.addonSnapshots, "addon");
    registerCatalogGroup(record.discountSnapshots, "discount");
    if (requestPath.includes("/ai/") && typeof record.service === "string") {
      registerCatalogName(record.service, "service");
    }
    Object.values(record).forEach(visit);
  }
  visit(payload);
}

function translateRegisteredCatalogText(value: string): string {
  const exact = registeredCatalogNames.get(value);
  if (exact) return exact.translation;
  const matches = [...registeredCatalogNames.entries()]
    .filter(([source]) => value.includes(source))
    .sort(([left], [right]) => right.length - left.length);
  if (matches.length === 0) return value;
  let protectedText = value;
  const replacements: string[] = [];
  for (const [source, entry] of matches) {
    if (!protectedText.includes(source)) continue;
    const token = `\uE000${replacements.length}\uE001`;
    protectedText = protectedText.replaceAll(source, token);
    replacements.push(entry.translation);
  }
  return protectedText.replace(/\uE000(\d+)\uE001/gu, (_match, index: string) => replacements[Number(index)] ?? "");
}

export function translateText(value: string, locale: AppLocale): string {
  if (locale === "zh-CN" || !value) return value;
  if (value.includes("\n")) return value.split("\n").map((line) => translateText(line, locale)).join("\n");
  const leading = value.match(/^\s*/u)?.[0] ?? "";
  const trailing = value.match(/\s*$/u)?.[0] ?? "";
  const core = value.slice(leading.length, value.length - trailing.length || undefined);
  const exact = ENGLISH_TRANSLATIONS[core];
  if (exact !== undefined) return `${leading}${exact}${trailing}`;
  for (const [pattern, format] of DYNAMIC_TRANSLATIONS) {
    const match = pattern.exec(core);
    if (match) return `${leading}${format(...match.slice(1))}${trailing}`;
  }
  const catalogText = translateRegisteredCatalogText(core);
  return catalogText === core ? value : `${leading}${catalogText}${trailing}`;
}

